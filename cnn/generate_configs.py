"""Generate every CNN and µMoE config used in the thesis from configs/base.yaml.

Writes:
  configs/backbones/<backbone>_<loss>.yaml       backbone sweep, BCE and ASL (Sec. 4.3)
  configs/asl_ablation/gpos<g>.yaml              ASL ablation on EfficientNetV2-M (Sec. 4.2.2)
  configs/mcloss/<hierarchy>.yaml                MCLoss with the full and restricted hierarchies (Sec. 4.2.3)
  ../interpretability/mumoe/configs/<cp|tr>_n<N>.yaml   µMoE heads (Sec. 4.5)

Usage:
    python generate_configs.py
"""
import argparse
import copy
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))

BACKBONES = [
    "resnet50", "resnet101", "resnext50_32x4d", "resnext101_32x8d",
    "densenet121", "densenet169",
    "efficientnet_b0", "efficientnet_v2_s", "efficientnet_v2_m", "efficientnet_v2_l",
    "convnext_tiny", "convnext_small",
    "convnextv2_tiny.fcmae_ft_in1k", "convnextv2_base.fcmae_ft_in1k",
]

# (gamma_pos, gamma_neg, clip) as in Table 5.2
ASL_ABLATION = {"gpos0": (0, 4, 0.02), "gpos1": (1, 4, 0.02), "gpos2": (2, 4, 0.05)}

# descendant matrices written by data/umls_hierarchy/
MCLOSS_HIERARCHIES = {
    "full": "umls_descendant_matrix.npz",
    "anatomy": "umls_descendant_matrix_anatomy.npz",
    "cooc1": "umls_descendant_matrix_live.npz",
    "cooc5": "umls_descendant_matrix_live_5.npz",
}

N_EXPERTS = [32, 64, 128, 256]


def write(cfg, path, run_root, group, name, header):
    run_dir = "/".join(p for p in (run_root, group, name) if p)
    cfg["paths"]["checkpoints"] = f"{run_dir}/checkpoints/"
    cfg["paths"]["logs"] = f"{run_dir}/logs/"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(f"# Generated by cnn/generate_configs.py from configs/base.yaml. {header}\n")
        yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)
    print("wrote", os.path.relpath(path, HERE))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base-config", default=os.path.join(HERE, "configs", "base.yaml"))
    ap.add_argument("--run-root", default="$WORK/Long-Tailed-Medical-Concept-Detection/runs")
    args = ap.parse_args()

    with open(args.base_config) as f:
        base = yaml.safe_load(f)
    artifacts = os.path.dirname(base["paths"]["mlb"])
    cnn_root = f"{args.run_root}/cnn"

    for backbone in BACKBONES:
        for loss in ("bce", "asl"):
            cfg = copy.deepcopy(base)
            cfg["model"]["backbone"] = backbone
            cfg["loss"]["type"] = loss
            name = f"{backbone}_{loss}"
            write(cfg, os.path.join(HERE, "configs", "backbones", f"{name}.yaml"),
                  cnn_root, "backbones", name, f"backbone={backbone} loss={loss}")

    for name, (gpos, gneg, clip) in ASL_ABLATION.items():
        cfg = copy.deepcopy(base)
        cfg["loss"]["type"] = "asl"
        cfg["loss"]["asl"] = {"gamma_neg": gneg, "gamma_pos": gpos, "clip": clip}
        write(cfg, os.path.join(HERE, "configs", "asl_ablation", f"{name}.yaml"),
              cnn_root, "asl_ablation", name, f"gamma_pos={gpos} gamma_neg={gneg} clip={clip}")

    for name, matrix in MCLOSS_HIERARCHIES.items():
        cfg = copy.deepcopy(base)
        cfg["loss"]["type"] = "mcloss"
        cfg["paths"]["descendant_matrix"] = f"{artifacts}/{matrix}"
        write(cfg, os.path.join(HERE, "configs", "mcloss", f"{name}.yaml"),
              cnn_root, "mcloss", name, f"hierarchy={name}")

    mumoe_dir = os.path.join(HERE, "..", "interpretability", "mumoe", "configs")
    for head, short in (("cpmumoe", "cp"), ("trmumoe", "tr")):
        for n in N_EXPERTS:
            cfg = copy.deepcopy(base)
            cfg["model"]["head_type"] = head
            cfg["model"]["mumoe"]["n_experts"] = n
            cfg["loss"]["type"] = "asl"
            name = f"{short}_n{n}"
            write(cfg, os.path.join(mumoe_dir, f"{name}.yaml"),
                  f"{args.run_root}/mumoe", "", name, f"head={head} n_experts={n} loss=asl")


if __name__ == "__main__":
    main()
